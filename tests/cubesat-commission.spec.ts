import { expect, test, type Page } from '@playwright/test'
import type { Game } from '../src/game/types'

import { button, configure, enterMeeting, finishWork, firstBrief, meeting, reveal, useStudioClock, work } from './studio-controls'
const radio = (page: Page, name: RegExp) => page.getByRole('radio', { name })
const persisted = (page: Page): Promise<Game> => page.evaluate(() => JSON.parse(localStorage.getItem('space-mission.single.v2')!))

async function start(page: Page, seed: number, { bay = false, rideshare = false, capability }: {
  bay?: boolean; rideshare?: boolean; capability?: RegExp
} = {}) {
  await page.goto(`/?seed=${seed}`)
  await firstBrief(page)
  if (bay) await radio(page, /Bay discharge survey/).check()
  await button(page, 'Accept commission').click()
  await enterMeeting(page)
  if (rideshare) await configure(page, /^Launch and orbit/, /Rideshare to sun-synchronous orbit/)
  if (capability) await configure(page, /^Observation capability/, capability)
  if (!(await meeting(page).isVisible())) await button(page, 'Compare designs').click()
  await work(page, /^Confirm initial configuration/)
}

async function integrate(page: Page) {
  await work(page, /^Freeze design/)
  await work(page, /^Build and test subsystems/)
  await work(page, /^Run integration tests/)
  await reviewConditions(page)
  await enterMeeting(page)
  await reveal(page, 'Integration evidence')
  await expect(page.getByText(/first transmission T\+32 min.*minimum silence 30 min/).filter({ visible: true })).toBeVisible()
}

async function pass(page: Page) {
  await reviewConditions(page)
  await button(page, 'Submit FRR').click()
  await button(page, 'Go to mission control').click()
  await button(page, 'Run first ground pass').click()
}

async function reviewConditions(page: Page) {
  const review = button(page, 'Review release conditions')
  if (await review.isVisible()) await review.click()
}

test('a first playthrough presents the prologue, teaches each stage and launches in real time', async ({ page }, info) => {
  test.setTimeout(45_000)
  await page.setViewportSize({ width: 489, height: 826 })
  await page.goto('/?seed=1')
  await button(page, 'Begin game').click()
  await expect(page.getByText(/avionics warning keeps coming back/)).toBeVisible()
  await button(page, 'Next').click()
  await expect(page.getByText(/has signed the release/)).toBeVisible()
  await button(page, 'Next').click()
  await expect(page.locator('.studio-scene')).toHaveAttribute('data-visual-step', 'liftoff')
  await button(page, 'Next').click()
  await expect(page.getByText(/never established what caused the loss/)).toBeVisible()
  await button(page, 'Next').click()
  await expect(page.getByText('Astra Dynamics · Two years later')).toBeVisible()
  await button(page, 'View the two commissions').click()
  await expect(page.getByRole('radio')).toHaveCount(2)
  await button(page, 'Accept commission').click()

  const lab = page.locator('.studio-scene')
  const instruction = page.locator('.studio-tutorial-target')
  await expect(page.getByText(/Rescue crews need 2 usable images/)).toBeVisible()
  await expect(lab).toHaveAttribute('data-scene', 'lab')
  await expect(button(page, 'Compare designs')).toHaveCount(0)
  await enterMeeting(page)
  await expect(lab).toHaveAttribute('data-scene', 'meeting')
  await expect(instruction).toContainText(/Feasibility checks/)
  await expect(button(page, 'Compare designs')).toBeFocused()
  await expect(page.locator('.studio-files')).toHaveAttribute('inert', '')
  await button(page, 'Compare designs').click()
  const forecast = meeting(page).locator('.studio-preview')
  const original = await forecast.innerText()
  await configure(page, /^Launch and orbit/, /Rideshare to sun-synchronous orbit/)
  await expect(forecast).toContainText('5 nominal downlink slots')
  await configure(page, /^Launch and orbit/, /ISS cargo flight/)
  await configure(page, /^Observation capability/, /Add an auxiliary sensor/)
  await expect.poll(() => forecast.innerText()).not.toBe(original)
  await expect(forecast).toContainText('Estimated first-pass delivery')
  await expect(forecast).toContainText('3.8 / 4 kg')
  await expect(forecast).toContainText('9 / 10 W')
  await expect(forecast).toContainText('66 cr')
  await configure(page, /^Observation capability/, /^Primary instrument/)
  await expect.poll(() => forecast.innerText()).toBe(original)
  await page.waitForTimeout(650)
  await lab.screenshot({ path: info.outputPath('meeting.png') })

  const assign = async (label: RegExp, task: string, ms: number, step: RegExp) => {
    await button(page, label).click()
    await expect(page.locator('.studio-run')).toHaveAttribute('data-work', task)
    const save = await persisted(page)
    expect(save.studioWork!.endsAt - save.studioWork!.startedAt).toBe(ms)
    expect(save.log.filter(entry => entry.id === task)).toHaveLength(0)
    if (task === 'assess') {
      await page.waitForTimeout(420)
      await lab.screenshot({ path: info.outputPath('crossing.png') })
    }
    if (task === 'integrate') {
      await page.waitForTimeout(450)
      await lab.screenshot({ path: info.outputPath('walking.png') })
      await page.waitForTimeout(1400)
      await lab.screenshot({ path: info.outputPath('at-workstation.png') })
    }
    await expect(instruction).toContainText(step, { timeout: ms + 1500 })
    expect((await persisted(page)).log.filter(entry => entry.id === task)).toHaveLength(1)
  }
  await assign(/^Confirm initial configuration/, 'assess', 4000, /Detailed design/)
  await assign(/^Freeze design/, 'freeze', 4000, /Manufacturing/)
  await assign(/^Build and test subsystems/, 'build', 6000, /Integration tests/)
  await assign(/^Run integration tests/, 'integrate', 6000, /Flight review/)
  await expect(page.getByText(/All integration checks passed/)).toBeVisible()
  await page.waitForTimeout(700)
  await lab.screenshot({ path: info.outputPath('reporting.png') })
  await expect(page.locator('.studio-next [inert]').filter({ hasText: 'Call a meeting' })).toHaveCount(1)
  await reviewConditions(page)
  await expect(button(page, 'Call a meeting')).toBeEnabled()
  await button(page, 'Submit FRR').click()
  const launch = page.locator('[data-launch-phase]')
  await expect(launch).toHaveAttribute('data-launch-phase', 'countdown')
  await expect(launch).toHaveAttribute('data-launch-phase', 'ignition')
  await expect(launch).toHaveAttribute('data-launch-phase', 'liftoff')
  await expect(lab).toHaveAttribute('data-scene', 'launchControl')
  await button(page, 'Run first ground pass').click()
  await expect(page.getByRole('heading', { name: 'Commission fulfilled', exact: true })).toBeVisible()
  expect((await persisted(page)).studioTutorial).toEqual(['feasibility', 'design', 'build', 'integration', 'review'])
})

