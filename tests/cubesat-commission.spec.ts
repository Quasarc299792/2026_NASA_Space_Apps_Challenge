test('a blocked design waits for meeting entry after reload and a saved correction settles once', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await start(page, 6, { rideshare: true, capability: /Add an auxiliary sensor/ })
  await integrate(page)

  const lab = page.locator('.studio-scene')
  await expect(lab).toHaveAttribute('data-warning', 'true')
  const room = meeting(page)
  await expect(room).toBeVisible()
  await expect(lab).toHaveAttribute('data-scene', 'meeting')
  await expect(room.locator('.option-art')).toHaveCount(2)
  const before = await persisted(page)
  await page.reload()
  await button(page, 'Continue mission').click()
  await expect(page.getByText(/frames are unreadable/)).toBeVisible()
  await page.clock.fastForward(10_000)
  await expect(lab).toHaveAttribute('data-scene', 'lab')
  await expect(room).toHaveCount(0)
  await expect(button(page, 'Enter meeting')).toBeVisible()
  await button(page, 'Enter meeting').click()
  await expect(room).toBeVisible()
  expect(await persisted(page)).toEqual(before)
  await button(page, '繁中').click()
  await expect(room.getByRole('heading')).toHaveText('受影響的需求')
  await expect(room.getByText(/還需要|時間少了/)).toBeVisible()
  await button(page, 'EN').click()
  const correction = button(page, /Return to the primary instrument/)
  await correction.evaluate(node => { (node as HTMLButtonElement).click(); (node as HTMLButtonElement).click() })
  await expect(page.locator('.studio-run')).toHaveAttribute('data-work', 'strip')
  const pending = await persisted(page)
  expect(pending.credits).toBe(before.credits)
  await page.reload()
  await button(page, 'Continue mission').click()
  await expect(page.locator('.studio-run')).toHaveAttribute('data-work', 'strip')
  expect((await persisted(page)).studioWork).toEqual(pending.studioWork)
  await useStudioClock(page)
  await finishWork(page)
  await expect(room).toHaveCount(0)
  await expect(lab).toHaveAttribute('data-auxiliary', 'false')
  await expect(lab).toHaveAttribute('data-visual-step', 'test')
  expect((await persisted(page)).log.filter(entry => entry.id === 'strip')).toHaveLength(1)
  expect((await persisted(page)).credits).toBe(before.credits - 4)
  await work(page, /Retest integration/)
  await pass(page)
  await expect(page.getByRole('heading', { name: 'Commission fulfilled' })).toBeVisible()
})
